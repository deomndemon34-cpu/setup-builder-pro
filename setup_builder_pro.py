def generate_affiliate_link(item_name, current_link=""):
    if current_link and "tag=" in current_link:
        return current_link
    query = urllib.parse.quote(str(item_name))
    return f"https://www.amazon.com/s?k={query}&tag={AMAZON_TAG}"

# --- 📄 PDF GENERATION FUNCTION ---
def clean_pdf_text(text):
    """Prevents encoding errors with emojis or special characters in FPDF."""
    replacements = {"€": "EUR", "’": "'", "«": '"', "»": '"', "—": "-"}
    for k, v in replacements.items():
        text = text.replace(k, v)
    return text.encode("latin-1", "ignore").decode("latin-1")

def generate_pdf(df, total, budget, score, setup_name="My Setup"):
    pdf = FPDF()
    pdf.add_page()
    
    # Header
    pdf.set_fill_color(30, 41, 59)
    pdf.rect(0, 0, 210, 35, 'F')
    pdf.set_text_color(255, 255, 255)
    pdf.set_font("Arial", "B", 18)
    pdf.cell(0, 12, clean_pdf_text(f"SETUP BUILDER PRO - {setup_name.upper()}"), ln=True, align="C")
    pdf.set_font("Arial", "", 10)
    pdf.cell(0, 6, "Generated by Lucas Tech Studio", ln=True, align="C")
    
    pdf.ln(15)
    
    # Financial summary
    pdf.set_text_color(0, 0, 0)
    pdf.set_font("Arial", "B", 12)
    pdf.cell(0, 8, clean_pdf_text(f"Max Budget: {budget:.2f} EUR  |  Total Cost: {total:.2f} EUR  |  Balance Score: {score}/100"), ln=True)
    pdf.ln(5)
    
    # Table header
    pdf.set_fill_color(226, 232, 240)
    pdf.set_font("Arial", "B", 10)
    pdf.cell(40, 8, "Category", 1, 0, "L", True)
    pdf.cell(95, 8, "Item", 1, 0, "L", True)
    pdf.cell(30, 8, "Price", 1, 0, "R", True)
    pdf.cell(25, 8, "Status", 1, 1, "C", True)
    
    # Table rows
    pdf.set_font("Arial", "", 10)
    for _, row in df.iterrows():
        cat = clean_pdf_text(str(row["Category"]))
        item = clean_pdf_text(str(row["Item"]))[:45]
        price = f"{row['Price (€)']:.2f} EUR"
        status = "Purchased" if row["Purchased"] else "To buy"
        
        pdf.cell(40, 8, cat, 1)
        pdf.cell(95, 8, item, 1)
        pdf.cell(30, 8, price, 1, 0, "R")
        pdf.cell(25, 8, status, 1, 1, "C")
        
    pdf.ln(10)
    pdf.set_font("Arial", "I", 9)
    pdf.set_text_color(100, 116, 139)
    pdf.cell(0, 6, "Tip: Find direct links to these components on our web application.", ln=True)
    
    return bytes(pdf.output())

# --- 🧠 ANALYSIS LOGIC ---
def analyze_setup(df, budget):
    total = df["Price (€)"].sum()
    if total == 0:
        return 0, []
    pc_cost = df[df["Category"] == "PC / Tower"]["Price (€)"].sum()
    screen_cost = df[df["Category"] == "Monitor"]["Price (€)"].sum()
    periph_cost = df[df["Category"].isin(["Peripherals", "Audio"])]["Price (€)"].sum()
    
    score = 100
    tips = []
    if pc_cost > 1200 and screen_cost < 180:
        score -= 25
        tips.append("⚠️ **Visual bottleneck:** Your PC is very powerful, but your monitor might limit your FPS (aim for at least 144Hz / 1440p).")
    if pc_cost > 0 and screen_cost == 0:
        score -= 30
        tips.append("🖥️ **Critical omission:** No monitor in your list.")
    if pc_cost > 800 and periph_cost < 50:
        score -= 15
        tips.append("⌨️ **Comfort overlooked:** Save some budget for a good keyboard and mouse.")
    if (pc_cost / total) > 0.80:
        score -= 20
        tips.append("📊 **Imbalance:** Over 80% of your budget is going solely into the PC tower.")
    if total > budget:
        score -= 10
    return max(0, score), tips

